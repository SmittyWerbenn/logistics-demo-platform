#!/usr/bin/env python3
"""Reads assets/Price List Website Sinar trans.xlsx and writes api-worker/migrations/0043_ongkir_pricelist.sql.
Usage: python3 api-worker/scripts/generate-ongkir-rates.py"""
import re, zipfile, os
import xml.etree.ElementTree as ET
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
XLSX = os.path.join(ROOT, "assets", "Price List Website Sinar trans.xlsx")
OUT = os.path.join(ROOT, "api-worker", "migrations", "0043_ongkir_pricelist.sql")
M = "{http://schemas.openxmlformats.org/spreadsheetml/2006/main}"
z = zipfile.ZipFile(XLSX)
ss = ["".join(t.text or "" for t in si.iter(M + "t")) for si in ET.fromstring(z.read("xl/sharedStrings.xml")).findall(M + "si")]

def sheet(n):
    out = []
    for row in ET.fromstring(z.read(f"xl/worksheets/sheet{n}.xml")).iter(M + "row"):
        r = {}
        for c in row.findall(M + "c"):
            v = c.find(M + "v")
            if v is None: continue
            col = re.match(r"[A-Z]+", c.get("r")).group()
            r[col] = ss[int(v.text)].strip() if c.get("t") == "s" else v.text
        out.append(r)
    return out

def num(s):
    m = re.search(r"\d+", s or "")
    return int(m.group()) if m else None

def lead(s):
    nums = [int(x) for x in re.findall(r"\d+", s or "")]
    if not nums: return (1, 1)
    mult = 7 if re.search(r"minggu", s, re.I) else 1
    return (nums[0] * mult, nums[-1] * mult)

def q(s): return "'" + s.replace("'", "''") + "'"

rows = []
def add(hub, mode, grp, kota, rate, rate15, minkg, est, sort):
    a, b = lead(est)
    rows.append((hub, mode, grp, kota, rate, rate15, minkg, est, a, b, sort))

for n, hub in ((1, "JKT"), (3, "SUB")):
    data = sheet(n); sort = 0; grp = "Lainnya"
    for blk in (("C","D","E","F"),("H","I","J","K"),("N","O","P","Q"),("S","T","U","V")):
        # the H block continues the province the C block ended on; N and S open with their own heading
        for r in data:
            name = r.get(blk[0], "").strip()
            if not name or name.lower().startswith(("tujuan", "dari")): continue
            rate = num(r.get(blk[1]))
            if rate is None:
                if r.get(blk[2]) is None: grp = name
                continue
            sort += 1
            add(hub, "CARGO", grp, name, rate, None, num(r.get(blk[2])) or 50, r.get(blk[3], "").strip(), sort)

for n, hub in ((2, "JKT"), (4, "SUB")):
    sort = 0
    for r in sheet(n):
        name = r.get("C", "").strip()
        rate = num(r.get("E"))
        if not name or rate is None or name.lower().startswith("tujuan"): continue
        sort += 1
        add(hub, "KERETA", "Jawa", name, rate, num(r.get("D")), num(r.get("F")) or 50, r.get("G", "").strip(), sort)

sql = ["-- Generated by api-worker/scripts/generate-ongkir-rates.py from assets/Price List Website Sinar trans.xlsx. Do not edit by hand.",
"CREATE TABLE IF NOT EXISTS ongkir_rates (",
"  id INTEGER PRIMARY KEY AUTOINCREMENT,",
"  origin_hub TEXT NOT NULL CHECK (origin_hub IN ('JKT','SUB')),",
"  mode TEXT NOT NULL CHECK (mode IN ('CARGO','KERETA')),",
"  grp TEXT NOT NULL,",
"  kota TEXT NOT NULL,",
"  tarif_per_kg INTEGER NOT NULL,",
"  tarif_1_5kg INTEGER,",
"  min_kg INTEGER NOT NULL DEFAULT 50,",
"  estimasi_text TEXT NOT NULL DEFAULT '',",
"  lead_min INTEGER NOT NULL DEFAULT 1,",
"  lead_max INTEGER NOT NULL DEFAULT 1,",
"  sort INTEGER NOT NULL DEFAULT 0",
");",
"CREATE INDEX IF NOT EXISTS idx_ongkir_rates_lookup ON ongkir_rates(origin_hub, mode, kota);",
"DELETE FROM ongkir_rates;"]
for r in rows:
    h, m, g, k, rt, r15, mk, est, a, b, s = r
    sql.append(f"INSERT INTO ongkir_rates (origin_hub,mode,grp,kota,tarif_per_kg,tarif_1_5kg,min_kg,estimasi_text,lead_min,lead_max,sort) VALUES ({q(h)},{q(m)},{q(g)},{q(k)},{rt},{r15 if r15 is not None else 'NULL'},{mk},{q(est)},{a},{b},{s});")
open(OUT, "w").write("\n".join(sql) + "\n")
print(len(rows), "rows ->", OUT)
from collections import Counter
print(Counter((r[0], r[1]) for r in rows)); print(Counter(r[2] for r in rows))
